"""Live real-TOWN evidence for ResonanceBFT — actual nandatown agents, real LLM opinions.

Unlike the standalone ``demo.py`` (which calls the protocol directly), this drives the REAL
committed scenario YAMLs through the framework's ``ScenarioRunner``: a leader agent proposes,
follower agents seal their pentadic evaluations and reply over the in-memory transport, the
leader resolves the n−f quorum and broadcasts the committed Outcome — exactly the town flow the
e2e tests exercise. The only difference here is that each honest agent's opinion is generated by
a real LLM (key-free subscription CLI, lowest/fastest tier) and injected via the scenario's
``opinions`` config hook, instead of the scripted stance.

It runs every scenario (genuine / silent-crash / byzantine / partition / bag-of-words) at every
tier, N reps each, and writes a timestamped EVIDENCE_<ts>.md (each run kept, never overwriting a
prior report). It is NOT part of the plugin and NOT run in CI: it is
invoked by the ``live``-marked test or by hand, so it never affects the hackathon submission.

    python evidence_town.py                       # full matrix → EVIDENCE.md
    python evidence_town.py --tiers mock,claude:haiku --reps 1

Tiers are lowest-thinking / smallest models only (claude haiku, codex low reasoning, agy Gemini
Flash Low) — the consensus outcome does not need a frontier model, and this keeps the run fast.
"""

