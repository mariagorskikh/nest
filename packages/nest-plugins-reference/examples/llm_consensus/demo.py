"""Real-LLM ResonanceBFT consensus demo — LLM agents form opinions, the protocol agrees.

Each agent's OPINION is generated by an LLM (or a deterministic mock), sealed at
``participate()``, and the ``n−f`` quorum commit + genuine-vs-superficial audit run
DETERMINISTICALLY over the sealed vectors. This is the "transformer-at-the-edge,
deterministic core" design: the LLM's nondeterminism is frozen at seal time (per agent),
so it informs perception but never forks the commit.

Run (offline, deterministic mock LLM — no keys, no network):
    python demo.py
    python demo.py --scales 4,7,12,20

Run with a REAL LLM (nondeterministic — a demonstration, not a test):
    # subscription CLI, NO API KEY (uses your local claude/codex/agy login). Lowest/fastest
    # models are plenty — the deterministic core does not need a frontier model:
    python demo.py --backend claude --model haiku --scales 4,7
    python demo.py --backend codex --scales 4
    python demo.py --backend agy --model "Gemini 3.5 Flash (Low)" --scales 4
    # local, no key: install ollama, `ollama pull llama3.2`
    python demo.py --backend ollama --model llama3.2 --scales 4,7
    # any OpenAI-compatible endpoint:
    OPENAI_API_KEY=... OPENAI_BASE_URL=https://api.openai.com/v1 \
        python demo.py --backend openai --model gpt-4o-mini

Optional dense (attention) embedding on the semantic axis so the stance audit bites:
    python demo.py --embed fastembed        # pip install fastembed   (no torch)

The paper *Can AI Agents Agree?* (Berdoz et al. 2026, arXiv:2603.01213) finds real LLM
Byzantine consensus is unreliable, dominated by LIVENESS failures — which ResonanceBFT
targets with its n−f commit + bounded-round HK convergence. This demo is where you can
watch that play out with real models.
"""

