# ── LLM backends ────────────────────────────────────────────────────────────────
def _mock_llm(persona: dict[str, str], question: str) -> str:
    """Deterministic stand-in: a plausible 1-sentence opinion from the persona's lean/angle."""
    lean, angle = persona["lean"], persona["angle"]
    verb = {"support": "approve", "oppose": "reject", "neutral": "hold"}[lean]
    stance = {
        "support": f"I approve — {angle}, so we should adopt it.",
        "oppose": f"I reject this — {angle}, it is too risky to adopt now.",
        "neutral": f"I would hold — {angle}; let us gather more data before we decide.",
    }[lean]
    return f"{stance} ({verb})"


def _ollama_llm(model: str) -> LlmFn:
    def call(persona: dict[str, str], question: str) -> str:
        prompt = (
            f"You are a {persona['name']} whose angle is: {persona['angle']}. "
            f"In ONE or TWO sentences, give your honest opinion on: {question} "
            f"Your general lean is to {persona['lean']} it. Be specific and take a clear stance."
        )
        body = json.dumps({"model": model, "prompt": prompt, "stream": False}).encode()
        req = urllib.request.Request(
            "http://localhost:11434/api/generate",
            data=body,
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=120) as resp:  # noqa: S310 (localhost)
            return json.loads(resp.read())["response"].strip()

    return call


def _openai_llm(model: str) -> LlmFn:
    base = os.environ.get("OPENAI_BASE_URL", "https://api.openai.com/v1").rstrip("/")
    key = os.environ.get("OPENAI_API_KEY", "")

    def call(persona: dict[str, str], question: str) -> str:
        prompt = (
            f"You are a {persona['name']} whose angle is: {persona['angle']}. "
            f"In ONE or TWO sentences, give your honest opinion on: {question} "
            f"Your general lean is to {persona['lean']} it. Be specific and take a clear stance."
        )
        body = json.dumps(
            {"model": model, "messages": [{"role": "user", "content": prompt}], "temperature": 0.7}
        ).encode()
        req = urllib.request.Request(
            f"{base}/chat/completions",
            data=body,
            headers={"Content-Type": "application/json", "Authorization": f"Bearer {key}"},
        )
        with urllib.request.urlopen(req, timeout=120) as resp:  # noqa: S310
            return json.loads(resp.read())["choices"][0]["message"]["content"].strip()

    return call


# Locally-authenticated agent CLIs usable as key-free LLM backends. Each shells out to a
# headless one-shot invocation and returns the model's clean text response — exactly like an
# API call, but billed to the interactive subscription login. Model switching is uniform via
# --model where the subscription tier permits it. All three are verified working on this
# machine: claude (Anthropic), codex (ChatGPT account), agy (Antigravity — Gemini/Claude/GPT
# models). `agy models` lists the menu, e.g. "Gemini 3.1 Pro (High)", "Claude Opus 4.6".
_CLI_BACKENDS = ("claude", "codex", "agy")


def _cli_llm(backend: str, model: str) -> LlmFn:
    """Generate opinions via a locally-authenticated subscription CLI — no API key needed.

    Shells out to `claude -p`, `codex exec`, or `agy -p`, dropping the metered API-key env var
    (where one exists) so the CLI uses its interactive login. This is the key-free way to drive
    the consensus with a real frontier model, and supports switching models per backend.
    """
    import subprocess
    import tempfile
    import time

    def call(persona: dict[str, str], question: str) -> str:
        prompt = (
            f"You are a {persona['name']} whose angle is: {persona['angle']}. "
            f"In ONE sentence, give your honest opinion on: {question} "
            f"Your lean is to {persona['lean']} it. Output ONLY the one-sentence opinion, "
            f"nothing else."
        )
        env = dict(os.environ)
        # Isolate each call to a throwaway cwd so no project CLAUDE.md / AGENTS.md / repo file
        # leaks into the prompt — the calls then behave like a bare stateless API. (Claude's
        # `--bare` would also strip global auto-memory, but it forces ANTHROPIC_API_KEY auth,
        # defeating the key-free subscription login, so we keep OAuth + cwd isolation instead.)
        with tempfile.TemporaryDirectory(prefix="rbft_llm_") as cwd:

            def run(argv: list[str], timeout: int) -> subprocess.CompletedProcess[str]:
                # Subscription CLIs occasionally fail a call transiently (rate limits, flaky
                # sockets). Retry with backoff so one hiccup does not poison a whole town run.
                last: Exception | None = None
                for attempt in range(3):
                    try:
                        return subprocess.run(  # noqa: S603
                            argv,
                            capture_output=True,
                            text=True,
                            timeout=timeout,
                            env=env,
                            stdin=subprocess.DEVNULL,
                            cwd=cwd,
                            check=True,
                        )
                    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
                        last = exc
                        if attempt < 2:
                            time.sleep(2.0 * (attempt + 1))
                raise last  # type: ignore[misc]  # unreachable with last=None

            if backend == "claude":
                env.pop("ANTHROPIC_API_KEY", None)
                # --no-session-persistence: no transcript written to disk, cannot be resumed.
                argv = [
                    backend,
                    "-p",
                    prompt,
                    "--no-session-persistence",
                    *(["--model", model] if model else []),
                ]
                return _clean(run(argv, 180).stdout)
            if backend == "agy":  # Antigravity CLI; auth is its own subscription login
                argv = [backend, "-p", prompt, *(["--model", model] if model else [])]
                return _clean(run(argv, 300).stdout)
            # codex prints a session preamble to stdout; -o writes ONLY the final message.
            # model_reasoning_effort=low: a one-sentence opinion needs no deep reasoning, and
            # codex defaults to xhigh (~10x slower) — low keeps each call to a few seconds.
            env.pop("OPENAI_API_KEY", None)
            last = os.path.join(cwd, "last.txt")
            argv = [
                backend,
                "exec",
                "--skip-git-repo-check",
                "-c",
                "model_reasoning_effort=low",
                "-o",
                last,
                *(["-m", model] if model else []),
                prompt,
            ]
            run(argv, 300)
            with open(last, encoding="utf-8") as fh:
                return _clean(fh.read())

    return call


def _clean(text: str) -> str:
    return " ".join(text.strip().splitlines()).strip() or "(no response)"


def make_llm(backend: str, model: str) -> LlmFn:
    if backend == "mock":
        return _mock_llm
    if backend == "ollama":
        return _ollama_llm(model or "llama3.2")
    if backend == "openai":
        return _openai_llm(model or "gpt-4o-mini")
    if backend in _CLI_BACKENDS:  # subscription CLI, no API key
        return _cli_llm(backend, model)
    raise SystemExit(
        f"unknown --backend {backend!r} (use mock|ollama|openai|{'|'.join(_CLI_BACKENDS)})"
    )


def make_embed(kind: str) -> Callable[[str], list[float]] | None:
    if kind == "none":
        return None
    import importlib

    if kind == "fastembed":
        fe = importlib.import_module("fastembed").TextEmbedding("BAAI/bge-small-en-v1.5")
        return lambda t: list(fe.embed([t]))[0].tolist()
    if kind == "model2vec":
        _sm = importlib.import_module("model2vec").StaticModel
        m = _sm.from_pretrained("minishlab/potion-base-8M")
        return lambda t: [float(x) for x in m.encode([t])[0].tolist()]
    raise SystemExit(f"unknown --embed {kind!r} (use none|fastembed|model2vec)")


def _print_outcome(m: dict[str, Any]) -> None:
    print("\n" + pentadic_summary(m))
    cq: dict[str, Any] = m.get("consensus_quality", {})
    fa = cq.get("false_agreement_rate", "n/a (bag-of-words; use --embed fastembed)")
    print(
        f"\nOutcome: {m['status'].upper()}   quorum {m['quorum_size']}/{m['quorum_needed']}"
        f"   (n={m['total_participants']}, f={m['f']})"
    )
    print(f"  consensus_type : {m.get('consensus_type', 'unknown')}")
    print(f"  false_agreement: {fa}")
    print(
        f"  quality        : independence={cq.get('independence_rate', '-')}"
        f"  capitulation={cq.get('capitulation_rate', '-')}"
        f"  collapse={cq.get('disagreement_collapse', '-')}"
    )
    print(
        f"  tampered       : {m.get('tampered_agents', [])}"
        f"   tampered_exceeds_f={m.get('tampered_exceeds_f')}"
    )


def _evil_label(i: int, byzantine: int, garbage: int) -> str:
    if i < byzantine:
        return "[BYZANTINE — tampers seal]"
    if i < byzantine + garbage:
        return "[MALFORMED — garbage vector]"
    return ""


async def run_round(
    title: str,
    question: str,
    opinions: list[str],
    embed_fn: Callable[[str], list[float]] | None,
    backend: str,
    embed_kind: str,
    *,
    byzantine: int = 0,
    garbage: int = 0,
    note: str = "",
) -> dict[str, Any]:
    """One consensus round; injects `byzantine` (broken-seal) and `garbage` (non-finite)
    records AFTER participate() so resolve() must detect them. Returns the outcome metadata."""
    n = len(opinions)
    bar = "=" * 74
    faults = (
        f"byzantine={byzantine}, malformed={garbage}" if (byzantine or garbage) else "no faults"
    )
    print(f"\n{bar}\n {title}   (n={n}, LLM: {backend}, embed: {embed_kind}, {faults})\n{bar}")
    print(f"Question: {question}\nOpinions:")
    agents = [
        ResonanceBFT(AgentId(f"a{i}"), seed=i, expected_n=n, embed_fn=embed_fn) for i in range(n)
    ]
    task = Task(id="llm-consensus", description=question)
    for i, opinion in enumerate(opinions):
        task.metadata[f"eval_a{i}"] = opinion
        print(f"  a{i:<2} {_evil_label(i, byzantine, garbage):<28} {opinion}")

    rnd = await agents[0].propose(task, all_agents=[f"a{i}" for i in range(n)])
    for a in agents:
        await a.participate(rnd)
    # Adversarial injection: mutate the sealed record so the SHA-256 seal no longer matches.
    ev = rnd.metadata["evaluations"]
    for i in range(byzantine):
        sem = ev[f"a{i}"].get("semantic", [0.0])
        ev[f"a{i}"]["semantic"] = [x + 999.0 for x in sem]  # valid numbers, wrong belief
    for i in range(byzantine, byzantine + garbage):
        width = max(1, len(ev[f"a{i}"].get("semantic", [0.0])))
        ev[f"a{i}"]["semantic"] = [float("inf")] * width  # non-finite → schema-invalid

    m = (await agents[0].resolve(rnd)).metadata
    _print_outcome(m)
    if note:
        print(f"  → {note}")
    return m


