async def run_suite(
    embed_fn: Callable[[str], list[float]] | None, backend: str, embed_kind: str
) -> None:
    print(
        "\nAdversarial + quality suite. Theme: a COMMIT is not the same as genuine agreement —\n"
        "the protocol commits a coherent n−f quorum, the AUDIT (consensus_type / false_agreement\n"
        "/ quality) tells you whether that commit is real, tampered records are detected and\n"
        "excluded, and it ABORTS (no consensus) when faults exceed the tolerance f."
    )
    for case in SUITE:
        await run_round(
            case["title"],
            case["question"],
            case["opinions"],
            embed_fn,
            backend,
            embed_kind,
            byzantine=case.get("byzantine", 0),
            garbage=case.get("garbage", 0),
            note=case["note"],
        )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--backend",
        default="mock",
        help="mock | ollama | openai | claude | codex | agy "
        "(claude/codex/agy = key-free subscription CLIs)",
    )
    ap.add_argument("--model", default="", help="LLM model name for ollama/openai")
    ap.add_argument("--embed", default="none", help="none | fastembed | model2vec")
    ap.add_argument("--scales", default="4,7,12", help="comma-separated agent counts")
    ap.add_argument("--question", default=DEFAULT_QUESTION)
    ap.add_argument(
        "--suite",
        action="store_true",
        help="run the adversarial + quality suite (genuine / false / coerced / evil / malformed)"
        " instead of the scale sweep",
    )
    args = ap.parse_args()

    embed_fn = make_embed(args.embed)
    if args.suite:
        asyncio.run(run_suite(embed_fn, args.backend, args.embed))
        return

    llm = make_llm(args.backend, args.model)
    scales = [int(s) for s in args.scales.split(",") if s.strip()]
    for n in scales:
        opinions = [llm(PERSONAS[i % len(PERSONAS)], args.question) for i in range(n)]
        asyncio.run(
            run_round(
                f"SCALE: {n} agents",
                args.question,
                opinions,
                embed_fn,
                args.backend,
                args.embed,
            )
        )
    if args.backend == "mock":
        print("\n(Deterministic mock LLM. For real models: --backend ollama|openai.)")


if __name__ == "__main__":
    main()
